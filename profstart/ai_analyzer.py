def analyze_student_profile(
    scores: Dict[str, int],
    open_answer: str = "",
    track_goal: str = "пока изучаю варианты",
) -> Dict[str, Any]:
    """
    Строит личностно-ориентированный профиль на основе баллов по шкалам характера и мышления,
    ключевых маркеров из свободного ответа и выбранного формата траектории.
    """
    adjusted_scores: Dict[str, float] = {
        key: float(scores.get(key, 0)) for key in PROFILES.keys()
    }

    text_lower = (open_answer or "").lower()
    matched_keywords: List[str] = []

    for key, profile in PROFILES.items():
        for kw in profile["keywords"]:
            if kw in text_lower:
                adjusted_scores[key] += 1.5
                if kw not in matched_keywords:
                    matched_keywords.append(kw)

    total = sum(adjusted_scores.values()) or 1.0
    ranked = sorted(adjusted_scores.items(), key=lambda item: item[1], reverse=True)

    breakdown = []
    for key, val in ranked:
        percent = round((val / total) * 100)
        breakdown.append({
            "code": key,
            "title": PROFILES[key]["title"],
            "character_traits": PROFILES[key]["character_traits"],
            "score": round(val, 1),
            "percent": percent,
            "roles": PROFILES[key]["roles"],
            "universities": PROFILES[key]["universities"],
            "spb_focus": PROFILES[key]["spb_focus"],
            "track_tip": PROFILES[key]["track_tips"].get(
                track_goal, PROFILES[key]["track_tips"]["пока изучаю варианты"]
            ),
        })

    top_item = breakdown[0]
    second_item = breakdown[1]

    personality_portrait = (
        f"По твоим ответам в тебе заметны {top_item['character_traits']}. "
        f"Плюс фоном тянется «{second_item['title']}» ({second_item['percent']}%) — "
        f"из-за этого ты не застреваешь в одном шаблоне и можешь подстраиваться под задачу."
    )

    summary = (
        f"Сильнее всего сейчас звучит «{top_item['title']}» ({top_item['percent']}%). "
        f"Этот трек хорошо стыкуется с тем, как ты привык(ла) думать и действовать в обычной жизни."
    )

    return {
        "top_profile": top_item,
        "secondary_profile": second_item,
        "personality_portrait": personality_portrait,
        "breakdown": breakdown,
        "matched_keywords": matched_keywords[:8],
        "track_goal": track_goal,
        "summary": summary,
    }